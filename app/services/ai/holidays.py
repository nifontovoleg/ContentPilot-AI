def get_holiday(d: date) -> str:
    return RU_HOLIDAYS.get((d.month, d.day), "")


def get_trend_for_date(d: date, seed: int = 0) -> str:
    """Детерминированно подбираем тренд по дате."""
    idx = (d.day + d.month * 3 + seed) % len(TRENDS)
    return TRENDS[idx]


def get_month_event(month: int, idx: int = 0) -> str:
    events = MONTHLY_EVENTS.get(month, [])
    if not events:
        return ""
    return events[idx % len(events)]
